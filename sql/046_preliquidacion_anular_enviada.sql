-- =============================================================================
-- Migration 046: anular una preliquidación ya enviada a SIESA (liberar sus recepciones)
-- =============================================================================
--
-- Caso de uso: una preliquidación se cerró (o sigue abierta) con datos erróneos, p. ej. un conteo de
-- animales equivocado, y el costo de lo enviado quedó mal. Las entradas oficiales (CEA) YA se anularon
-- a mano en SIESA. Hoy `carnes_preliq_anular` (041) solo funciona mientras nada salió a SIESA y
-- `anularSede` mantiene la sede dentro de la misma preliquidación. Aquí se anula la preliquidación
-- completa y se LIBERAN sus recepciones para vincularlas a otra preliquidación abierta de la especie.
--
-- Qué hace:
--   1. Tabla de auditoría carnes_preliquidacion_sedes_anuladas: la fila completa de cada sede liberada
--      (jsonb) más cuándo, quién y por qué. `carnes_preliquidacion_sedes.recepcion_id` es UNIQUE: la sede
--      de la preliquidación anulada se borra para que la recepción pueda tener otra sede; el historial
--      queda aquí.
--   2. carnes_preliq_anular_enviada(p_id, p_version, p_orden_version, p_por, p_motivo), bajo lock
--      (cabecera -> sedes -> recepciones, por id ascendente):
--        - cabecera `abierta` o `cerrada` (liquidada o no); `anulada` es no_anulable(ya_anulada);
--        - rechaza toda la operación si hay una sede enviando/sin_confirmar o un envío oficial
--          enviando/sin_confirmar (ambiguo en SIESA: el admin lo resuelve antes) -> sede_ambigua;
--        - rechaza si alguna recepción tiene una CEI de vísceras vigente (visceras_recepcion /
--          ajuste_visceras): fuera de alcance -> visceras_vigentes;
--        - rechaza si un envío oficial vigente cubre además recepciones de otras preliquidaciones
--          -> envio_compartido;
--        - rechaza si un saldo que ella originó ya se aplicó en otra preliquidación -> saldo_aplicado;
--        - marca como `anulado` los envíos oficiales vigentes (ok/duplicado) de las recepciones, con
--          por/motivo (misma regla que `anularOficialRecepcion`: libera el candado de sql/010) y limpia
--          siesa_at de la recepción;
--        - archiva las sedes, borra sus avisos sin enviar y las borra;
--        - libera cada recepción: preliquidacion_id NULL, estado Aprobado (como una recepción de
--          talleres recién finalizada), costeado_at/siesa_at NULL y costos de los renglones limpios.
--          inicial_omitida_* NO se toca;
--        - saldos igual que `carnes_preliq_anular`: los que consumió o tenía dirigidos vuelven a
--          `pendiente` hacia la abierta sin liquidar más antigua de la especie (o sin destino); los
--          propios pendientes pasan a `descartado`;
--        - cabecera -> `anulada` con anulada_at/por y motivo_anulacion; sube version y orden_version.
--      No habla con SIESA ni manda correos.
--
-- Contrato de retorno: JSONB `{resultado: ...}`. SECURITY INVOKER (por defecto). Idempotente (IF NOT EXISTS +
-- CREATE OR REPLACE). Todo o nada.
--
-- Precondición: 038 a 041 aplicadas (y 011: columnas de anulación de carnes_siesa_envios).
-- Orden de despliegue: ... -> 045 -> 046 -> backend con POST /api/preliquidaciones/:id/anular-enviada.
-- Reversión: sql/046_rollback.sql.
-- =============================================================================

BEGIN;
SET LOCAL lock_timeout = '5s';

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_proc WHERE proname = 'carnes_preliq_anular') THEN
    RAISE EXCEPTION 'Falta carnes_preliq_anular. Corra sql/041_preliquidacion_rpc_correcciones.sql antes de esta migración.';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_name = 'carnes_siesa_envios' AND column_name = 'anulado_por'
  ) THEN
    RAISE EXCEPTION 'Falta sql/011_siesa_anulacion.sql (columnas de anulación de carnes_siesa_envios).';
  END IF;
END $$;


-- -----------------------------------------------------------------------------
-- Auditoría de las sedes liberadas. Sin FK a la recepción ni a la sede (que ya no existe): el historial
-- sobrevive a lo que se borre después.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_sedes_anuladas (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sede_id           BIGINT        NOT NULL,
  preliquidacion_id BIGINT        NOT NULL REFERENCES carnes_preliquidaciones(id),
  recepcion_id      BIGINT        NOT NULL,
  estado_sede       VARCHAR(20)   NOT NULL,
  fila              JSONB         NOT NULL,
  anulada_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
  anulada_por       VARCHAR(120),
  motivo            TEXT          NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_carnes_preliq_sedes_anuladas_preliq
  ON carnes_preliquidacion_sedes_anuladas (preliquidacion_id);
CREATE INDEX IF NOT EXISTS idx_carnes_preliq_sedes_anuladas_recepcion
  ON carnes_preliquidacion_sedes_anuladas (recepcion_id);

COMMENT ON TABLE carnes_preliquidacion_sedes_anuladas IS
  'Sedes liberadas al anular una preliquidación ya enviada a SIESA (sql/046): fila completa en `fila`, más quién, cuándo y por qué.';


-- -----------------------------------------------------------------------------
-- carnes_preliq_anular_enviada(p_id, p_version, p_orden_version, p_por, p_motivo)
--
-- Resultados: ok | no_anulable(motivo) | version_cambiada | no_encontrada | motivo_requerido
--   motivos de no_anulable: ya_anulada | sede_ambigua | visceras_vigentes | envio_compartido | saldo_aplicado
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION carnes_preliq_anular_enviada(
  p_id            BIGINT,
  p_version       INTEGER,
  p_orden_version INTEGER,
  p_por           TEXT,
  p_motivo        TEXT
) RETURNS JSONB AS $fn$
DECLARE
  v_header        carnes_preliquidaciones%ROWTYPE;
  v_recs          BIGINT[];
  v_destinos      BIGINT[];
  v_destino_nuevo BIGINT;
  v_sedes         INTEGER;
  v_envios        INTEGER;
  v_reasignados   INTEGER := 0;
  v_motivo        TEXT;
BEGIN
  v_motivo := NULLIF(btrim(COALESCE(p_motivo, '')), '');
  IF v_motivo IS NULL THEN
    RETURN jsonb_build_object('resultado', 'motivo_requerido');
  END IF;

  SELECT * INTO v_header FROM carnes_preliquidaciones WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('resultado', 'no_encontrada');
  END IF;
  IF v_header.estado NOT IN ('abierta', 'cerrada') THEN
    RETURN jsonb_build_object('resultado', 'no_anulable', 'motivo', 'ya_anulada');
  END IF;

  PERFORM 1 FROM carnes_preliquidacion_sedes WHERE preliquidacion_id = p_id ORDER BY id FOR UPDATE;
  SELECT COALESCE(array_agg(recepcion_id ORDER BY recepcion_id), '{}'::BIGINT[]) INTO v_recs
    FROM carnes_preliquidacion_sedes WHERE preliquidacion_id = p_id;
  PERFORM 1 FROM carnes_recepciones WHERE id = ANY (v_recs) ORDER BY id FOR UPDATE;

  -- Ambiguo en SIESA: una sede enviando/sin_confirmar, o un envío oficial en vuelo o sin confirmar.
  IF EXISTS (
    SELECT 1 FROM carnes_preliquidacion_sedes s
     WHERE s.preliquidacion_id = p_id AND s.estado IN ('enviando', 'sin_confirmar')
  ) OR EXISTS (
    SELECT 1 FROM carnes_siesa_envios e
     WHERE e.tipo = 'oficial'
       AND e.estado IN ('enviando', 'sin_confirmar')
       AND (e.recepcion_id = ANY (v_recs) OR e.recepcion_ids && v_recs)
  ) THEN
    RETURN jsonb_build_object('resultado', 'no_anulable', 'motivo', 'sede_ambigua');
  END IF;

  -- Vísceras CEI vigentes: fuera de alcance (la CEI se anula por su propio flujo).
  IF EXISTS (
    SELECT 1 FROM carnes_siesa_envios e
     WHERE e.tipo IN ('visceras_recepcion', 'ajuste_visceras')
       AND e.estado IN ('enviando', 'ok', 'duplicado', 'sin_confirmar')
       AND (e.recepcion_id = ANY (v_recs) OR e.recepcion_ids && v_recs)
  ) THEN
    RETURN jsonb_build_object('resultado', 'no_anulable', 'motivo', 'visceras_vigentes');
  END IF;

  -- Un oficial vigente que cubre además recepciones ajenas no se puede marcar anulado desde aquí.
  IF EXISTS (
    SELECT 1 FROM carnes_siesa_envios e
     WHERE e.tipo = 'oficial'
       AND e.estado IN ('ok', 'duplicado')
       AND e.recepcion_ids IS NOT NULL
       AND (e.recepcion_id = ANY (v_recs) OR e.recepcion_ids && v_recs)
       AND NOT (e.recepcion_ids <@ v_recs)
  ) THEN
    RETURN jsonb_build_object('resultado', 'no_anulable', 'motivo', 'envio_compartido');
  END IF;

  IF EXISTS (
    SELECT 1 FROM carnes_preliquidacion_saldos
     WHERE origen_preliquidacion_id = p_id AND estado = 'aplicado'
  ) THEN
    RETURN jsonb_build_object('resultado', 'no_anulable', 'motivo', 'saldo_aplicado');
  END IF;

  IF v_header.version <> p_version OR v_header.orden_version <> p_orden_version THEN
    RETURN jsonb_build_object('resultado', 'version_cambiada');
  END IF;

  -- Cabeceras destino de saldos (mismo criterio y orden de bloqueo que carnes_preliq_anular).
  SELECT COALESCE(array_agg(DISTINCT destino_preliquidacion_id), '{}'::BIGINT[]) INTO v_destinos
    FROM carnes_preliquidacion_saldos
   WHERE origen_preliquidacion_id = p_id AND estado = 'pendiente' AND destino_preliquidacion_id IS NOT NULL;

  IF EXISTS (
    SELECT 1 FROM carnes_preliquidacion_saldos
     WHERE destino_preliquidacion_id = p_id AND estado IN ('aplicado', 'pendiente')
  ) THEN
    SELECT id INTO v_destino_nuevo
      FROM carnes_preliquidaciones
     WHERE especie = v_header.especie AND estado = 'abierta' AND liquidada_at IS NULL AND id <> p_id
     ORDER BY created_at, id
     LIMIT 1;
  END IF;
  PERFORM 1 FROM carnes_preliquidaciones
   WHERE id = ANY (array_remove(v_destinos || v_destino_nuevo, NULL)) ORDER BY id FOR UPDATE;
  IF v_destino_nuevo IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM carnes_preliquidaciones
     WHERE id = v_destino_nuevo AND estado = 'abierta' AND liquidada_at IS NULL
  ) THEN
    v_destino_nuevo := NULL;
  END IF;

  -- Los oficiales ya se anularon a mano en SIESA: se refleja acá (libera el candado de sql/010).
  UPDATE carnes_siesa_envios
     SET estado = 'anulado',
         anulado_por = NULLIF(p_por, ''),
         anulado_at = now(),
         motivo_anulacion = v_motivo
   WHERE tipo = 'oficial'
     AND estado IN ('ok', 'duplicado')
     AND (recepcion_id = ANY (v_recs) OR recepcion_ids && v_recs);
  GET DIAGNOSTICS v_envios = ROW_COUNT;

  -- Auditoría y borrado de las sedes (recepcion_id es UNIQUE: la recepción queda libre).
  INSERT INTO carnes_preliquidacion_sedes_anuladas (
    sede_id, preliquidacion_id, recepcion_id, estado_sede, fila, anulada_por, motivo
  )
  SELECT s.id, s.preliquidacion_id, s.recepcion_id, s.estado, to_jsonb(s), NULLIF(p_por, ''), v_motivo
    FROM carnes_preliquidacion_sedes s
   WHERE s.preliquidacion_id = p_id;

  DELETE FROM carnes_preliquidacion_alertas
   WHERE enviado_ok = false
     AND (preliquidacion_id = p_id OR sede_id IN (SELECT id FROM carnes_preliquidacion_sedes WHERE preliquidacion_id = p_id));
  DELETE FROM carnes_preliquidacion_sedes WHERE preliquidacion_id = p_id;
  GET DIAGNOSTICS v_sedes = ROW_COUNT;

  -- Liberar las recepciones: como una de talleres recién finalizada (Aprobado), sin costos ni vínculo.
  UPDATE carnes_recepcion_items
     SET costo_ajustado = NULL, costo_total = NULL
   WHERE recepcion_id = ANY (v_recs);
  UPDATE carnes_recepciones
     SET estado = 'Aprobado', costeado_at = NULL, siesa_at = NULL
   WHERE id = ANY (v_recs) AND estado IN ('Costeado', 'Enviado_SIESA');
  UPDATE carnes_recepciones
     SET siesa_at = NULL
   WHERE id = ANY (v_recs) AND siesa_at IS NOT NULL;
  UPDATE carnes_recepciones
     SET preliquidacion_id = NULL
   WHERE id = ANY (v_recs);

  -- Saldos (igual que carnes_preliq_anular).
  UPDATE carnes_preliquidacion_saldos
     SET estado = 'pendiente', destino_preliquidacion_id = v_destino_nuevo, updated_at = now()
   WHERE destino_preliquidacion_id = p_id AND estado IN ('aplicado', 'pendiente');
  GET DIAGNOSTICS v_reasignados = ROW_COUNT;

  UPDATE carnes_preliquidacion_saldos
     SET estado = 'descartado', editado_por = COALESCE(NULLIF(p_por, ''), editado_por), updated_at = now()
   WHERE origen_preliquidacion_id = p_id AND estado = 'pendiente';
  UPDATE carnes_preliquidaciones SET version = version + 1 WHERE id = ANY (v_destinos);
  IF v_destino_nuevo IS NOT NULL AND v_reasignados > 0 AND NOT (v_destino_nuevo = ANY (v_destinos)) THEN
    UPDATE carnes_preliquidaciones SET version = version + 1 WHERE id = v_destino_nuevo;
  END IF;

  UPDATE carnes_preliquidaciones
     SET estado = 'anulada',
         anulada_at = now(),
         anulada_por = NULLIF(p_por, ''),
         motivo_anulacion = v_motivo,
         version = version + 1,
         orden_version = orden_version + 1
   WHERE id = p_id;

  RETURN jsonb_build_object(
    'resultado', 'ok',
    'preliquidacion_id', p_id,
    'sedes_liberadas', v_sedes,
    'recepciones', to_jsonb(v_recs),
    'envios_anulados', v_envios,
    'saldos_reasignados', v_reasignados,
    'saldos_destino_id', v_destino_nuevo
  );
END;
$fn$ LANGUAGE plpgsql;

COMMIT;

