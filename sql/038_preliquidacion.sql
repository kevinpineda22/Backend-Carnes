-- =============================================================================
-- Migration 038: preliquidación de talleres (res / cerdo)
-- =============================================================================
--
-- Una "preliquidación" reparte el costo de un lote de animales entre las sedes
-- (talleres) que lo reciben, ANTES de que exista una liquidación legada. No crea
-- filas en carnes_liquidaciones: los CHECKs y guardas de esa tabla no se tocan.
--
-- Qué agrega (todo ADITIVO e idempotente; nada existente se modifica salvo dos
-- cosas en carnes_recepciones: la columna preliquidacion_id y dos CHECKs que solo
-- aplican a filas con preliquidacion_id):
--
--   carnes_preliquidacion_config     servicio por animal y ventana, por especie
--   carnes_preliquidacion_corridas   una fila por corrida (cron, barrido, admin, inmediata)
--   carnes_preliquidaciones          la cabecera (una por lote de animales)
--   carnes_preliquidacion_gastos     gastos manuales de la cabecera
--   carnes_preliquidacion_retomas    retomas del lote (cerdo)
--   carnes_preliquidacion_alternas   comparación informativa por servicio tardío
--   carnes_preliquidacion_sedes      una fila por sede vinculada (el CEA es por sede)
--   carnes_preliquidacion_saldos     saldos entre preliquidaciones (máquina de estados)
--   carnes_preliquidacion_alertas    cola de correos con deduplicación
--   carnes_recepciones.preliquidacion_id
--
-- Orden de creación (seguro para las FK): config, corridas, preliquidaciones,
-- gastos/retomas, alternas, sedes, saldos, alertas y, al final, el ALTER de
-- carnes_recepciones, que apunta a carnes_preliquidaciones.
--
-- NO hay fórmulas de negocio aquí: las decisiones viven en JS (src/shared) y las
-- RPC de sql/039+ solo bloquean, validan versiones y escriben el plan recibido.
--
-- Columnas de versión (optimistic locking): `version` e `orden_version` en la
-- cabecera; `version` y `costeo_orden_version` / `costeo_animales` en la sede, y
-- `claim_costeo_orden_version` / `correccion_orden_version` (M2) para decidir si
-- un envío puede limpiar `requiere_correccion`.
--
-- Orden de despliegue:
--
--   1. sql/038_preliquidacion.sql  ← esta, primero en QA y luego en producción
--   2. sql/039_preliquidacion_rpc.sql
--   3. Backend con CARNES_PRELIQUIDACION apagado
--   4. Frontend
--
-- Idempotente: se puede correr más de una vez. Todo o nada.
--
-- lock_timeout de 5s: si otra sesión retiene un lock sobre carnes_recepciones, TODO el
-- script aborta limpio (nada se aplica). Reintentar cuando la tabla esté libre.
-- =============================================================================

BEGIN;
SET LOCAL lock_timeout = '5s';

-- 0. Precondiciones.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_proc WHERE proname = 'carnes_set_updated_at') THEN
    RAISE EXCEPTION
      'Falta la función carnes_set_updated_at (sql/001_create_tables.sql). Correla antes de esta migración.';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.tables WHERE table_name = 'carnes_recepciones'
  ) OR NOT EXISTS (
    SELECT 1 FROM information_schema.tables WHERE table_name = 'carnes_siesa_envios'
  ) OR NOT EXISTS (
    SELECT 1 FROM information_schema.tables WHERE table_name = 'carnes_viceras_items'
  ) THEN
    RAISE EXCEPTION
      'Faltan tablas base (carnes_recepciones, carnes_siesa_envios o carnes_viceras_items). Correla sql/001 a sql/037 antes.';
  END IF;
END $$;


-- 1. Configuración por especie.
--    Un servicio por animal predeterminado por especie. 0 es un marcador: crear una
--    preliquidación se rechaza mientras valga 0 (`config_servicio_cero`).
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_config (
  especie              VARCHAR(10)   PRIMARY KEY CHECK (especie IN ('res', 'cerdo')),
  servicio_por_animal  NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (servicio_por_animal >= 0),
  ventana_dias         INTEGER       NOT NULL DEFAULT 2 CHECK (ventana_dias >= 1),
  created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now()
);

INSERT INTO carnes_preliquidacion_config (especie)
VALUES ('res'), ('cerdo')
ON CONFLICT (especie) DO NOTHING;


-- 2. Corridas: una fila por ejecución de cualquier origen.
--    `resumen.reevaluadas` guarda las sedes bloqueadas ya reevaluadas en la corrida.
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_corridas (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origen              VARCHAR(12)  NOT NULL
                        CHECK (origen IN ('schedule', 'sweep', 'dispatch', 'admin', 'inmediato')),
  gh_run_id           TEXT,
  estado              VARCHAR(10)  NOT NULL DEFAULT 'en_curso'
                        CHECK (estado IN ('en_curso', 'ok', 'error')),
  preliquidacion_ids  BIGINT[]     NOT NULL DEFAULT '{}',
  iniciada_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
  terminada_at        TIMESTAMPTZ,
  dry_run             BOOLEAN      NOT NULL DEFAULT false,
  resumen             JSONB        NOT NULL DEFAULT '{}'::jsonb,
  error               TEXT
);

CREATE INDEX IF NOT EXISTS idx_carnes_preliq_corridas_iniciada
  ON carnes_preliquidacion_corridas (iniciada_at DESC);


-- 3. Cabecera de la preliquidación.
CREATE TABLE IF NOT EXISTS carnes_preliquidaciones (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  especie                 VARCHAR(10)   NOT NULL CHECK (especie IN ('res', 'cerdo')),
  animales                INTEGER       NOT NULL CHECK (animales > 0),
  animal_en_pie           NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (animal_en_pie >= 0),
  servicio                NUMERIC(14,2),
  servicio_at             TIMESTAMPTZ,
  servicio_precorte       NUMERIC(14,2),
  servicio_precorte_at    TIMESTAMPTZ,
  servicio_por_animal     NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (servicio_por_animal >= 0),
  tercero_id              VARCHAR(30)   NOT NULL DEFAULT 'frigorifico',
  estado                  VARCHAR(10)   NOT NULL DEFAULT 'abierta'
                            CHECK (estado IN ('abierta', 'cerrada', 'anulada')),
  fecha_primer_ingreso    DATE,
  ventana_fin             TIMESTAMPTZ,
  liquidada_at            TIMESTAMPTZ,
  servicio_aplicado       NUMERIC(14,2),
  gasto_total_aplicado    NUMERIC(14,2),
  costo_por_animal        NUMERIC(14,2),
  version                 INTEGER       NOT NULL DEFAULT 0,
  orden_version           INTEGER       NOT NULL DEFAULT 0,
  aviso_ventana_at        TIMESTAMPTZ,
  cerrada_at              TIMESTAMPTZ,
  monto_no_asignado       NUMERIC(14,2),
  anulada_at              TIMESTAMPTZ,
  anulada_por             VARCHAR(120),
  motivo_anulacion        TEXT,
  creado_por              VARCHAR(120),
  created_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- A lo sumo una preliquidación abierta SIN iniciar por especie. La otra regla de
-- creación depende de now() y la aplica la RPC carnes_preliq_crear bajo un
-- advisory lock, porque now() no puede ir en el predicado de un índice.
CREATE UNIQUE INDEX IF NOT EXISTS uq_carnes_preliquidaciones_sin_iniciar
  ON carnes_preliquidaciones (especie)
  WHERE estado = 'abierta' AND fecha_primer_ingreso IS NULL;

CREATE INDEX IF NOT EXISTS idx_carnes_preliquidaciones_especie_estado
  ON carnes_preliquidaciones (especie, estado);


-- 4. Gastos manuales y retomas de la cabecera.
--    Los saldos NO se guardan aquí: la única fuente es carnes_preliquidacion_saldos.
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_gastos (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  preliquidacion_id BIGINT        NOT NULL REFERENCES carnes_preliquidaciones(id) ON DELETE CASCADE,
  concepto          VARCHAR(120)  NOT NULL,
  valor             NUMERIC(14,2) NOT NULL,
  signo             SMALLINT      NOT NULL DEFAULT 1 CHECK (signo IN (1, -1)),
  orden             INTEGER       NOT NULL DEFAULT 0,
  created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_carnes_preliq_gastos_preliq
  ON carnes_preliquidacion_gastos (preliquidacion_id, orden);

-- Retomas (cerdo): misma forma que carnes_liquidacion_retomas (sql/024).
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_retomas (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  preliquidacion_id BIGINT        NOT NULL REFERENCES carnes_preliquidaciones(id) ON DELETE CASCADE,
  vicera_item_id    BIGINT        REFERENCES carnes_viceras_items(id) ON DELETE SET NULL,
  nombre            VARCHAR(80)   NOT NULL,
  unidad            VARCHAR(5)    NOT NULL DEFAULT 'KL',
  kilos             NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (kilos >= 0),
  precio            NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (precio >= 0),
  precio_catalogo   NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (precio_catalogo >= 0),
  orden             INTEGER       NOT NULL DEFAULT 0,
  created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

  CONSTRAINT uq_carnes_preliq_retomas_item UNIQUE (preliquidacion_id, vicera_item_id)
);

CREATE INDEX IF NOT EXISTS idx_carnes_preliq_retomas_preliq
  ON carnes_preliquidacion_retomas (preliquidacion_id, orden);


-- 5. Alternas: comparación informativa cuando el servicio real llega tarde.
--    UNIQUE (preliquidacion_id, servicio_at) hace idempotente su generación.
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_alternas (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  preliquidacion_id BIGINT        NOT NULL REFERENCES carnes_preliquidaciones(id),
  servicio_real     NUMERIC(14,2) NOT NULL,
  servicio_at       TIMESTAMPTZ   NOT NULL,
  servicio_aplicado NUMERIC(14,2) NOT NULL,
  por_sede          JSONB         NOT NULL DEFAULT '[]'::jsonb,
  diferencia        NUMERIC(14,2) NOT NULL,
  created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

  UNIQUE (preliquidacion_id, servicio_at)
);


-- 6. Sedes vinculadas. Una recepción pertenece a una sola preliquidación (UNIQUE).
--    `estado` y `motivo_bloqueo` siguen la tabla de transiciones de
--    src/shared/preliquidacionEstados.js.
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_sedes (
  id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  preliquidacion_id           BIGINT        NOT NULL REFERENCES carnes_preliquidaciones(id),
  recepcion_id                BIGINT        NOT NULL UNIQUE REFERENCES carnes_recepciones(id),
  animales                    INTEGER       NOT NULL CHECK (animales > 0),
  orden                       INTEGER       NOT NULL,
  estado                      VARCHAR(20)   NOT NULL DEFAULT 'vinculada'
                                CHECK (estado IN (
                                  'vinculada', 'bloqueada', 'lista_para_enviar', 'calculada', 'enviando',
                                  'enviada', 'error', 'sin_confirmar', 'anulada', 'simulada'
                                )),
  motivo_bloqueo              VARCHAR(20)
                                CHECK (motivo_bloqueo IN (
                                  'excede_animales', 'utilidad_negativa', 'costeo_invalido', 'armado_invalido',
                                  'servicio_cero'
                                )),
  detalle_bloqueo             TEXT,
  liberada_at                 TIMESTAMPTZ,
  motivo_pendiente            VARCHAR(20)
                                CHECK (motivo_pendiente IN ('inicial_pendiente', 'reintentos_agotados')),
  requiere_correccion         BOOLEAN       NOT NULL DEFAULT false,
  gasto_sede                  NUMERIC(14,2),
  utilidad                    NUMERIC(14,2),
  servicio_compra             NUMERIC(14,2),
  valor_viceras               NUMERIC(14,2),
  valor_retomas               NUMERIC(14,2),
  costeo                      JSONB,
  envio_id                    BIGINT        REFERENCES carnes_siesa_envios(id) ON DELETE SET NULL,
  claim_token                 UUID,
  claimed_at                  TIMESTAMPTZ,
  calculado_at                TIMESTAMPTZ,
  version                     INTEGER       NOT NULL DEFAULT 0,
  costeo_orden_version        INTEGER,
  costeo_animales             INTEGER,
  claim_costeo_orden_version  INTEGER,
  correccion_orden_version    INTEGER,
  intentos                    INTEGER       NOT NULL DEFAULT 0,
  ultimo_intento_at           TIMESTAMPTZ,
  error_tipo                  VARCHAR(12)
                                CHECK (error_tipo IN ('transitorio', 'permanente')),
  ultima_corrida              BIGINT        REFERENCES carnes_preliquidacion_corridas(id),
  created_at                  TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at                  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_carnes_preliq_sedes_preliq_estado
  ON carnes_preliquidacion_sedes (preliquidacion_id, estado);


-- 7. Saldos entre preliquidaciones. `valor` con signo. Máquina de estados:
--    pendiente -> aplicado | movido | descartado.
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_saldos (
  id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origen_preliquidacion_id    BIGINT        NOT NULL REFERENCES carnes_preliquidaciones(id),
  especie                     VARCHAR(10)   NOT NULL CHECK (especie IN ('res', 'cerdo')),
  valor                       NUMERIC(14,2) NOT NULL,
  destino_preliquidacion_id   BIGINT        REFERENCES carnes_preliquidaciones(id),
  estado                      VARCHAR(12)   NOT NULL DEFAULT 'pendiente'
                                CHECK (estado IN ('pendiente', 'aplicado', 'movido', 'descartado')),
  ajuste_de_saldo_id          BIGINT        REFERENCES carnes_preliquidacion_saldos(id),
  movido_a_saldo_id           BIGINT        REFERENCES carnes_preliquidacion_saldos(id),
  alterna_id                  BIGINT        REFERENCES carnes_preliquidacion_alternas(id),
  editado_por                 VARCHAR(120),
  created_at                  TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at                  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_carnes_preliq_saldos_destino
  ON carnes_preliquidacion_saldos (destino_preliquidacion_id, estado);

CREATE INDEX IF NOT EXISTS idx_carnes_preliq_saldos_origen
  ON carnes_preliquidacion_saldos (origen_preliquidacion_id);


-- 8. Alertas: cola de correos con clave de deduplicación
--    (evento, preliquidacion_id, sede_id, ocurrencia). Sin FK a propósito: el
--    historial de lo enviado sobrevive a la fila que lo originó. Los 0 por defecto
--    evitan NULL en la clave única.
CREATE TABLE IF NOT EXISTS carnes_preliquidacion_alertas (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento            VARCHAR(40)  NOT NULL,
  preliquidacion_id BIGINT       NOT NULL DEFAULT 0,
  sede_id           BIGINT       NOT NULL DEFAULT 0,
  ocurrencia        BIGINT       NOT NULL DEFAULT 0,
  detalle           JSONB        NOT NULL DEFAULT '{}'::jsonb,
  enviado_ok        BOOLEAN      NOT NULL DEFAULT false,
  intentos_envio    INTEGER      NOT NULL DEFAULT 0,
  reclamada_at      TIMESTAMPTZ,
  enviado_at        TIMESTAMPTZ,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

  UNIQUE (evento, preliquidacion_id, sede_id, ocurrencia)
);

CREATE INDEX IF NOT EXISTS idx_carnes_preliq_alertas_pendientes
  ON carnes_preliquidacion_alertas (created_at)
  WHERE enviado_ok = false;


-- 9. Triggers updated_at.
DO $do$
DECLARE
  t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'carnes_preliquidacion_config',
    'carnes_preliquidaciones',
    'carnes_preliquidacion_gastos',
    'carnes_preliquidacion_retomas',
    'carnes_preliquidacion_sedes',
    'carnes_preliquidacion_saldos'
  ]
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_trigger WHERE tgname = 'set_updated_at_' || t AND tgrelid = t::regclass
    ) THEN
      EXECUTE format(
        'CREATE TRIGGER %I BEFORE UPDATE ON %I
           FOR EACH ROW EXECUTE FUNCTION carnes_set_updated_at()',
        'set_updated_at_' || t, t
      );
    END IF;
  END LOOP;
END;
$do$;


-- 10. carnes_recepciones: vínculo con la preliquidación.
--     ON DELETE RESTRICT: una preliquidación con recepciones vinculadas no se
--     borra; se anula (POST /:id/anular), que las desvincula primero.
ALTER TABLE carnes_recepciones
  ADD COLUMN IF NOT EXISTS preliquidacion_id BIGINT
    REFERENCES carnes_preliquidaciones(id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS idx_carnes_recepciones_preliquidacion
  ON carnes_recepciones (preliquidacion_id)
  WHERE preliquidacion_id IS NOT NULL;

-- Una recepción no puede estar a la vez en una liquidación legada y en una
-- preliquidación, y vinculada exige novillos entero > 0. El CHECK de novillos se
-- limita a preliquidacion_id IS NOT NULL: las filas legadas con 0 siguen
-- pudiéndose actualizar. La columna novillos conserva NUMERIC(10,2) (las
-- vísceras dependen de ella). Como preliquidacion_id es NULL en toda fila
-- existente, agregar estos CHECKs no revalida nada que pueda fallar.
DO $do$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'ck_carnes_recepciones_liq_xor_preliq'
  ) THEN
    ALTER TABLE carnes_recepciones
      ADD CONSTRAINT ck_carnes_recepciones_liq_xor_preliq
      CHECK (NOT (liquidacion_id IS NOT NULL AND preliquidacion_id IS NOT NULL));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'ck_carnes_recepciones_preliq_novillos'
  ) THEN
    ALTER TABLE carnes_recepciones
      ADD CONSTRAINT ck_carnes_recepciones_preliq_novillos
      CHECK (preliquidacion_id IS NULL OR (novillos > 0 AND novillos = trunc(novillos)));
  END IF;
END;
$do$;

COMMIT;

